#!/usr/bin/env node
/* Bakes the design system's token layer into the acceptance package as a module.

   The Project Intelligence Console is generated by the distributed CLI, and the design
   system is a private workspace package that is not part of the published tarball — the
   root `files` list does not carry it, and `workspace:*` cannot resolve from a registry.
   Importing it at runtime therefore works in this repository and fails everywhere else,
   which is exactly what the packed-CLI integration test caught.

   Generating the tokens at build time keeps a single source of truth (the design system)
   while leaving the shipped console with no runtime dependency on it. Drift is caught by
   tests/unit/console-design-tokens.test.ts, which regenerates and compares. */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const designSystemRoot = join(repoRoot, 'packages/design-system');
const outputPath = join(repoRoot, 'packages/acceptance/src/generated/design-system-tokens.ts');

/* The @import chain in styles/index.css, in order. Fonts are deliberately absent: the
   console must emit no external reference. */
const tokenLayerFiles = [
  'styles/tokens/colors.css',
  'styles/tokens/typography.css',
  'styles/tokens/spacing.css',
  'styles/tokens/effects.css',
  'styles/base.css'
];

export async function buildConsoleTokensModule() {
  const parts = await Promise.all(
    tokenLayerFiles.map(async (file) => (await readFile(join(designSystemRoot, file), 'utf8')).trim())
  );
  const css = parts.join('\n\n');

  if (/@import|url\(|https?:/i.test(css)) {
    throw new Error('design system token layer carries an external reference; the console must stay self-contained');
  }

  return [
    '/* GENERATED FILE — do not edit.',
    '   Source: packages/design-system/styles (token layer only, no fonts).',
    '   Regenerate: node scripts/generate-console-tokens.mjs',
    '',
    '   Baked in rather than imported because the design system is a private workspace',
    '   package that the published CLI tarball does not carry. */',
    '',
    `export const designSystemTokenCss = ${JSON.stringify(css)};`,
    ''
  ].join('\n');
}

/* pathToFileURL, not string interpolation: this repository's path contains a space, which
   import.meta.url percent-encodes and a raw `file://${argv[1]}` does not. */
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const contents = await buildConsoleTokensModule();
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, contents, 'utf8');
  console.log(`Console design tokens written: ${outputPath}`);
}
